class OutlierClipper(TransformerMixin, BaseEstimator):
    """Clip features to bounds fitted on the training data."""

    def __init__(self, method: str = "iqr", threshold: float = 1.5) -> None:
        self.method, self.threshold = method, threshold

    def fit(self, X, y=None):
        X = np.asarray(X, dtype=float)
        if self.method == "iqr":
            q1, q3 = np.nanpercentile(X, [25, 75], axis=0)
            self.lo_, self.hi_ = q1 - self.threshold * (q3 - q1), q3 + self.threshold * (q3 - q1)
        elif self.method == "zscore":
            mu, sd = np.nanmean(X, axis=0), np.nanstd(X, axis=0)
            self.lo_, self.hi_ = mu - self.threshold * sd, mu + self.threshold * sd
        else:
            self.lo_, self.hi_ = np.nanquantile(X, [self.threshold, 1 - self.threshold], axis=0)
        return self

    def transform(self, X):
        return np.clip(np.asarray(X, dtype=float), self.lo_, self.hi_)

    def get_feature_names_out(self, input_features=None):
        return np.asarray(input_features) if input_features is not None else None
