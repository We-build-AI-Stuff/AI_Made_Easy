def _data(graph: dict, framework: str) -> dict:
    nodes = [n for n in graph.get("nodes", []) if n.get("type", "").startswith("data.")]
    table = next((n for n in nodes if n["type"] in TABLES.get(framework, ())), None)
    if table is None:
        raise GroupsError("results by group read the run's table: it works for designs "
                          "trained on a CSV / Parquet table (data.csv)")
    params = table.get("params", {})
    if not params.get("path"):
        raise GroupsError("the run's table block has no file")
    return {"path": params["path"], "format": params.get("format") or "csv"}


def columns(mgr, run_id: str) -> dict:  # noqa: ANN001
    """The columns of the run's table, with how many different values each has."""
    import pandas as pd

    record = mgr.history.get(run_id)
    data = _data(record.graph, record.framework)
    path = Path(data["path"])
    if not path.is_file():
        raise GroupsError(f"the run's table is no longer at {path}")
    reader = {"parquet": pd.read_parquet, "tsv": lambda p: pd.read_csv(p, sep="\t")}.get(
        data["format"], pd.read_csv)
    frame = reader(path)
    out = []
    for name in frame.columns:
        values = frame[name]
        distinct = int(values.nunique())
        numeric = bool(pd.api.types.is_numeric_dtype(values))
        usable = distinct <= MAX_GROUPS or numeric
        out.append({"name": str(name), "distinct": distinct, "numeric": numeric,
                    "usable": usable,
                    "how": "quartiles" if numeric and distinct > QUARTILES_ABOVE else "values"})
    return {"run_id": run_id, "columns": out}


def write_script(workdir: Path, mgr, run_id: str, column: str) -> Path:  # noqa: ANN001
    from ai_made_easy.core.pipelines import stages as S

    record = mgr.history.get(run_id)
    source = mgr.history.path(run_id)
    data = _data(record.graph, record.framework)
    common = _COMMON.format(source=str(source), column=column, path=data["path"],
                            fmt=data["format"], max_groups=MAX_GROUPS,
                            quartiles=QUARTILES_ABOVE, min_positives=MIN_POSITIVES)
    if record.framework == "sklearn":
        found = sorted(source.glob("*_train_sklearn.py"))
        if not found or not any(source.glob("*_model.joblib")):
            raise GroupsError(f"run {run_id} saved no model to score")
        script = Path(workdir) / found[0].name
        shutil.copy2(found[0], script)
        text = script.read_text(encoding="utf-8")
        if "train_test_split(" not in text:
            raise GroupsError("this classic run has no test split to score")
        body = _CLASSIC.format(script=script.name, stratify="stratify=y if" in text)
    else:
        try:
            original = S.script_of(source)
        except FileNotFoundError as exc:
            raise GroupsError(f"run {run_id} has no training script to score with") from exc
        script = Path(workdir) / original.name
        shutil.copy2(original, script)
        text = script.read_text(encoding="utf-8")
        body = _TORCH.format(script=script.name,
                             drops_rows="keep = x.notna().all(axis=1)" in text)
    path = Path(workdir) / "stage_groups.py"
    path.write_text(common + body, encoding="utf-8")
    return path


def start(mgr, run_id: str, column: str) -> str:  # noqa: ANN001
    from ai_made_easy.core.graph import Graph

    record = mgr.history.get(run_id)
    if record.status != "finished":
        raise GroupsError(f"run {run_id} is {record.status}: score a finished run")
    if not column:
        raise GroupsError("pick a column to group by")
    _data(record.graph, record.framework)
    new_id = mgr.start_stage(Graph.from_dict(record.graph),
                             lambda wd: write_script(wd, mgr, run_id, column),
                             framework=record.framework, kind="groups",
                             project=record.project, tags=["groups"])
    mgr.history.update(new_id, note=f"Results of {run_id} ({record.name}) by {column!r}")
    return new_id


def summarize(raw: dict) -> dict:
    """Add the headline metric, each group's gap to the whole test set, and flags for
    groups clearly worse (a relative gap of at least GAP, with enough rows to trust)."""
    overall, groups = raw.get("overall", {}), raw.get("groups", [])
    metric = next((m for m in PRIMARY if m in overall), None)
    if metric is None:
        metric = next((k for k in overall if k != "count"), None)
    out = {**raw, "metric": metric, "higher_is_better": metric in HIGHER_IS_BETTER,
           "flagged": []}
    if metric is None:
        return out
    base = float(overall[metric])
    enough = max(10, int(0.02 * overall.get("count", 0)))
    for group in groups:
        value = group.get(metric)
        if value is None:
            continue
        diff = (base - value) if out["higher_is_better"] else (value - base)
        group["gap"] = diff / abs(base) if base else 0.0
        group["flagged"] = group["count"] >= enough and group["gap"] >= GAP
        if group["flagged"]:
            out["flagged"].append(group["value"])
    return out


def _rates(groups: list[dict], kind: str, i: int) -> list[tuple[float, str]]:
    return [(g["rates"][kind][i], g["value"]) for g in groups
            if g["rates"][kind][i] is not None]


def _overall(whole: dict, kind: str, i: int, rows: list[tuple[float, str]]) -> float:
    """A rate over all test rows, or the groups' mean when the run didn't record it."""
    values = whole.get(kind) or []
    if i < len(values) and values[i] is not None:
        return values[i]
    return sum(v for v, _ in rows) / len(rows)


def fairness(raw: dict) -> dict | None:
    """Gaps in predicted-class and error rates between groups with enough rows: the
    largest over the classes. Each group is compared with all test rows: it is flagged
    when it gets a class FAIR_GAP more or less often and outside four fifths of the
    overall rate, or its true-positive rate is FAIR_GAP or more below the overall one
    (or its false-positive rate that much above)."""
    classes = raw.get("classes")
    overall = raw.get("overall", {})
    enough = max(10, int(0.02 * overall.get("count", 0)))
    groups = [g for g in raw.get("groups", []) if g.get("rates") and g["count"] >= enough]
    if not classes or len(groups) < 2:
        return None
    whole = raw.get("overall_rates") or {}
    out = {"classes": classes, "parity_gap": 0.0, "parity_ratio": 1.0, "odds_gap": 0.0,
           "worst": {}, "flagged": []}
    flagged: set[str] = set()
    for i, name in enumerate(classes):
        selection, tpr, fpr = (_rates(groups, kind, i) for kind in ("selection", "tpr", "fpr"))
        if selection:
            top = max(v for v, _ in selection)
            gap = top - min(v for v, _ in selection)
            ratio = min(v for v, _ in selection) / top if top else 1.0
            if gap > out["parity_gap"]:   # the gap and ratio both describe this class
                out["worst"]["parity"] = name
                out["parity_gap"], out["parity_ratio"] = gap, ratio
            base = _overall(whole, "selection", i, selection)
            flagged |= {g for v, g in selection if abs(v - base) >= FAIR_GAP - _EXACT
                        and min(v, base) < FOUR_FIFTHS * max(v, base)}
        for kind, rows, sign in (("tpr", tpr, -1), ("fpr", fpr, 1)):
            if len(rows) < 2:
                continue
            gap = max(v for v, _ in rows) - min(v for v, _ in rows)
            if gap > out["odds_gap"]:
                out["worst"]["odds"] = (f"the {'true' if kind == 'tpr' else 'false'}-positive "
                                        f"rate{'' if len(classes) == 1 else f' of {name}'}")
            out["odds_gap"] = max(out["odds_gap"], gap)
            base = _overall(whole, kind, i, rows)
            flagged |= {g for v, g in rows if sign * (v - base) >= FAIR_GAP - _EXACT}
    out["flagged"] = sorted(flagged)
    out["summary"] = _fairness_text(out)
    return out


def _fairness_text(f: dict) -> str:
    """One paragraph both apps show."""
    which = f["worst"].get("parity", f["classes"][0])
    four_fifths = ", under the four-fifths rule" if f["parity_ratio"] < FOUR_FIFTHS else ""
    parity = (f"How often groups are predicted {which} differs by up to "
              f"{f['parity_gap']:.0%} (lowest/highest {f['parity_ratio']:.2f}{four_fifths}).")
    odds = (f"Error rates differ by up to {f['odds_gap']:.0%}"
            + (f" ({f['worst']['odds']})" if "odds" in f["worst"] else "") + ".")
    verdict = (f"Treated differently: {', '.join(f['flagged'])}." if f["flagged"]
               else "No group stands out.")
    return f"{parity} {odds} {verdict}"


def result(mgr, run_id: str) -> dict:  # noqa: ANN001
    status = mgr.status(run_id)
    out = {"run_id": run_id, "state": status.get("state"), "error": status.get("error") or ""}
    path = mgr.history.path(run_id) / RESULT
    if path.is_file():
        raw = json.loads(path.read_text(encoding="utf-8"))
        out.update(summarize(raw))
        out["fairness"] = fairness(raw)
        out["mitigation"] = mitigation(raw)
    return out


def mitigation(raw: dict) -> dict | None:
    """Per-group thresholds (binary classifiers), with fairness before and after on the
    rows they were not fitted on."""
    found = raw.get("mitigation")
    if not found:
        return None
    out = dict(found)
    for side in ("before", "after"):
        out[f"fairness_{side}"] = fairness({**found[side], "classes": raw.get("classes")})
    before, after = out["fairness_before"], out["fairness_after"]
    if before and after:
        out["helps"] = after["odds_gap"] < before["odds_gap"] - _EXACT
        change = (f"error rates differ by up to {after['odds_gap']:.0%} instead of "
                  f"{before['odds_gap']:.0%}, and accuracy is "
                  f"{found['after']['overall']['accuracy']:.1%} instead of "
                  f"{found['before']['overall']['accuracy']:.1%}")
        if out["helps"]:
            out["summary"] = (
                f"With a threshold per group (fitted on {found['fitted_on']}), {change}. "
                + (f"Still treated differently: {', '.join(after['flagged'])}."
                   if after["flagged"] else "No group stands out."))
        else:
            out["summary"] = (
                f"A threshold per group doesn't help here ({change}): the model's scores "
                "aren't just shifted for some groups. Try group weights (Class Balancing) "
                "or more data for the groups it gets wrong.")
    return out
