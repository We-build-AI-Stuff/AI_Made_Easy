# ------------------------------------------------------------------ losses

def _loss(type_id: str, params: dict, framework: str = "pytorch"):
    import torch
    from torch import nn

    from ai_made_easy.core.training import catalog as cat

    comp = cat.COMPONENTS[type_id]
    expr = cat.render(type_id, {**{s.name: s.default for s in comp.params}, **params}, framework)
    if framework == "keras":
        import keras
        from keras import ops

        return eval(expr, {"keras": keras, "ops": ops})  # noqa: S307
    ns = {"torch": torch, "nn": nn, "EMBED_DIM": 8, "NUM_CLASSES": 2}
    helper = comp.meta.get("torch_helper")
    if helper:
        exec(cat.TRAIN_HELPERS[helper], ns)  # noqa: S102
    return eval(expr, ns)  # noqa: S307


def test_polyloss_is_cross_entropy_plus_epsilon_times_one_minus_pt():
    torch = pytest.importorskip("torch")
    logits, y = torch.randn(6, 4), torch.tensor([0, 1, 2, 3, 0, 1])
    ce = torch.nn.functional.cross_entropy(logits, y)
    assert float(_loss("train.loss_poly", {"epsilon": 0.0})(logits, y)) == pytest.approx(float(ce))
    pt = logits.softmax(-1)[torch.arange(6), y]
    want = ce + 2.0 * (1 - pt).mean()
    assert float(_loss("train.loss_poly", {"epsilon": 2.0})(logits, y)) == pytest.approx(float(want))


@pytest.mark.parametrize("type_id,params", [
    ("train.loss_poly", {"epsilon": 1.0}), ("train.loss_charbonnier", {"epsilon": 0.01}),
    ("train.loss_asymmetric", {})])
def test_keras_losses_match_pytorch(type_id, params):
    torch = pytest.importorskip("torch")
    keras = pytest.importorskip("keras")
    torch.manual_seed(0)
    pred = torch.randn(5, 3)
    target = {"train.loss_poly": torch.tensor([0, 2, 1, 1, 0]),
              "train.loss_charbonnier": torch.randn(5, 3),
              "train.loss_asymmetric": (torch.rand(5, 3) > 0.5).float()}[type_id]
    want = float(_loss(type_id, params)(pred, target))
    got = _loss(type_id, params, "keras")(target.numpy(), pred.numpy())
    assert float(keras.ops.convert_to_numpy(keras.ops.mean(got))) == pytest.approx(want, rel=1e-4)


