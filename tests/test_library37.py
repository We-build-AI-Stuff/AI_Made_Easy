def _run(graph, tmp_path, monkeypatch):
    from ai_made_easy.core.codegen.training_gen import generate_training

    monkeypatch.chdir(tmp_path)
    code = generate_training(graph, "pytorch")
    ns: dict = {"__name__": "aime_training"}
    exec(compile(code, f"<{graph.name}>", "exec"), ns)  # noqa: S102
    ns["main"]()
    return code


def _test_metric(out: str, key: str) -> float:
    return float(out.split("test:")[-1].split(f"{key}=")[1].split()[0])


