def _metrics(keys: list[str]):
    import math

    import numpy as np

    from ai_made_easy.core.training import catalog as cat
    from ai_made_easy.core.training.metrics_code import metrics_code

    ids = {c.meta["key"]: c.type_id for c in cat.METRICS}
    ns = {"np": np, "math": math, "to_scores": lambda o: o}
    exec(metrics_code("regression", [(ids[k], {}, k) for k in keys]), ns)  # noqa: S102
    return ns["compute_metrics"]


def test_psnr_ccc_and_ssim():
    np = pytest.importorskip("numpy")
    rng = np.random.default_rng(0)
    y = rng.random((6, 1, 16, 16))
    noisy = y + rng.normal(scale=0.1, size=y.shape)
    got = _metrics(["psnr", "ccc", "ssim"])(noisy, y)
    mse = np.mean((noisy - y) ** 2)
    assert got["psnr"] == pytest.approx(10 * np.log10((y.max() - y.min()) ** 2 / mse))
    fp, ft = noisy.ravel(), y.ravel()
    ccc = 2 * np.cov(fp, ft, bias=True)[0, 1] / (fp.var() + ft.var() + (fp.mean() - ft.mean()) ** 2)
    assert got["ccc"] == pytest.approx(ccc)
    same = _metrics(["ssim", "ccc"])(y, y)
    assert same["ssim"] == pytest.approx(1.0) and same["ccc"] == pytest.approx(1.0)
    assert 0 < got["ssim"] < 0.95
    shifted = _metrics(["ccc"])(y + 1.0, y)["ccc"]              # perfectly correlated, offset
    assert shifted < 0.5


