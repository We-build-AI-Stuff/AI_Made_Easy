# ------------------------------------------------------------------ optimizers

def _optimizer(type_id: str, params, **kw):
    import torch
    from torch import nn

    from ai_made_easy.core.training import catalog as cat

    comp = cat.COMPONENTS[type_id]
    ns = {"torch": torch, "nn": nn}
    exec(cat.TRAIN_HELPERS[comp.meta["torch_helper"]], ns)  # noqa: S102
    return ns[comp.meta["torch_helper"]](params, **kw)


@pytest.mark.parametrize("type_id,kw", [("train.prodigy", {}),
                                        ("train.cautious_adamw", {"lr": 0.05}),
                                        ("train.yogi", {"lr": 0.05})])
def test_new_optimizers_fit_a_least_squares_problem(type_id, kw):
    torch = pytest.importorskip("torch")
    torch.manual_seed(0)
    x = torch.randn(200, 5)
    y = x @ torch.tensor([1.0, -2.0, 0.5, 3.0, 0.0]) + 0.01 * torch.randn(200)
    w = torch.zeros(5, requires_grad=True)
    opt = _optimizer(type_id, [w], **kw)
    for _ in range(300):
        opt.zero_grad()
        loss = ((x @ w - y) ** 2).mean()
        loss.backward()
        opt.step()
    assert float(loss) < 0.05, float(loss)


def test_cautious_adamw_matches_adamw_when_every_coordinate_agrees():
    torch = pytest.importorskip("torch")
    a = torch.nn.Parameter(torch.tensor([1.0, -2.0, 3.0]))
    b = torch.nn.Parameter(a.detach().clone())
    mine = _optimizer("train.cautious_adamw", [a], lr=0.1, weight_decay=0.01)
    ref = torch.optim.AdamW([b], lr=0.1, weight_decay=0.01)
    for p, opt in ((a, mine), (b, ref)):
        (p ** 2).sum().backward()
        opt.step()
    assert torch.allclose(a, b, atol=1e-6)


def test_prodigy_finds_a_step_size_larger_than_its_start():
    torch = pytest.importorskip("torch")
    w = torch.nn.Parameter(torch.full((10,), 5.0))
    opt = _optimizer("train.prodigy", [w])
    for _ in range(50):
        opt.zero_grad()
        (w ** 2).sum().backward()
        opt.step()
    assert opt.param_groups[0]["d"] > 1e-3 and float(w.abs().max()) < 5.0


