r"""mnist_mlp — Keras 3 training script generated by AI Made Easy.

Task:   multi-class classification (10 classes)
Data:   Torchvision mnist
Model:  mnist_mlp (101,770 trainable parameters)
Run:    python mnist_mlp_train_keras.py   (any Keras 3 backend: TensorFlow, JAX or PyTorch)
Needs:  keras>=3, numpy
"""
from __future__ import annotations

import json
import math
import pickle
import random
import time
from pathlib import Path

import keras
import numpy as np
from keras import layers

# ================================================================ config
SEED = 42
EPOCHS = 10
BATCH_SIZE = 32
EARLY_STOP = 3
GRAD_CLIP = 0.0
ACCUM_STEPS = 1
MIXED_PRECISION = False
LR0 = 0.001
VAL_FRACTION = 0.1
TEST_FRACTION = 0.1
SPLIT_SEED = 42
INPUT_SHAPE = (1, 28, 28)  # per sample, channels-first (as designed)
KERAS_TRANSPOSE = (0, 2, 3, 1)  # channels-first -> the model's Keras layout
NUM_CLASSES = 10
MODEL_FILE = "mnist_mlp_best.keras"
CALLBACKS = []          # more Keras callbacks for fit (e.g. the learning-rate finder)
COMPILE = False         # jit_compile (torch.compile on the PyTorch backend)
RESUME = False          # continue from RESUME_FILE (resume an interrupted run)
RESUME_FILE = "resume.weights.h5"   # weights and optimizer, saved after each epoch ("" = off)
CLASS_NAMES = None


# ================================================================= model
def build_model() -> keras.Model:
    inputs = keras.Input(shape=(28, 28, 1), dtype="float32", name="input")
    x = layers.Flatten()(inputs)
    x = layers.Dense(units=128, use_bias=True)(x)
    x = layers.ReLU()(x)
    x = layers.Dropout(rate=0.2)(x)
    x = layers.Dense(units=10, use_bias=True)(x)
    return keras.Model(inputs=inputs, outputs=x, name="mnist_mlp")

# ================================================================== data
INFERENCE_STATE: dict = {}  # fitted preprocessing, saved with the model for serving


def load_raw():
    r"""Load Torchvision mnist. Returns (features, targets, class names or None)."""
    (x_train, y_train), (x_test, y_test) = keras.datasets.mnist.load_data()
    x = np.concatenate([x_train, x_test]).astype(np.float32) / 255.0
    x = x[:, None] if x.ndim == 3 else x.transpose(0, 3, 1, 2)
    return x, np.concatenate([y_train, y_test]).reshape(-1), None


def split_indices(n: int, y) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Train / validation / test indices."""
    n_val, n_test = int(n * VAL_FRACTION), int(n * TEST_FRACTION)
    rng = np.random.default_rng(SPLIT_SEED)
    if y is not None and np.ndim(y) == 1 and len(np.unique(y)) < max(n // 5, 2):
        train, val, test = [], [], []
        for c in np.unique(y):
            members = np.flatnonzero(y == c)
            rng.shuffle(members)
            cv, ct = int(round(len(members) * VAL_FRACTION)), int(round(len(members) * TEST_FRACTION))
            val += list(members[:cv])
            test += list(members[cv:cv + ct])
            train += list(members[cv + ct:])
        return (rng.permutation(train), rng.permutation(val).astype(int),
                rng.permutation(test).astype(int))
    idx = rng.permutation(n)
    return idx[n_val + n_test:], idx[:n_val], idx[n_val:n_val + n_test]


class NumericPipeline:
    """Feature transforms fitted on training data only."""

    def fit(self, x: np.ndarray) -> "NumericPipeline":
        flat = x.reshape(len(x), -1)
        axes = (0,) + tuple(range(2, x.ndim))
        return self

    def _scale(self, x: np.ndarray) -> np.ndarray:
        shape = x.shape
        flat = x.reshape(len(x), -1).astype(np.float32)
        return flat.reshape(shape)

    def transform(self, x: np.ndarray) -> np.ndarray:
        x = self._scale(x)
        return x.astype(np.float32)


def make_arrays() -> dict[str, tuple[np.ndarray, np.ndarray]]:
    """Load, split and preprocess the data. Statistics come from the training split."""
    x, y, classes = load_raw()
    global CLASS_NAMES
    CLASS_NAMES = classes
    train_i, val_i, test_i = split_indices(len(y), y)
    parts = {"train": train_i, "val": val_i, "test": test_i}
    feats = {k: x[v] for k, v in parts.items()}
    targets = {k: np.asarray(y)[v] for k, v in parts.items()}
    pipeline = NumericPipeline().fit(feats["train"])
    INFERENCE_STATE["numeric"] = dict(vars(pipeline))
    feats = {k: pipeline.transform(v) for k, v in feats.items()}
    out = {}
    for k in parts:
        xs = feats[k]
        if xs.ndim == 2 and len(INPUT_SHAPE) > 1 and xs.shape[1] == int(np.prod(INPUT_SHAPE)):
            xs = xs.reshape(len(xs), *INPUT_SHAPE)
        if xs.shape[1:] != tuple(INPUT_SHAPE):
            raise SystemExit(f"data samples have shape {xs.shape[1:]} but the model expects "
                             f"{tuple(INPUT_SHAPE)}")
        out[k] = (xs, targets[k].astype(np.int64))
    return out


def prepare_inputs(raw: list) -> np.ndarray:
    """Raw inputs -> a model-ready batch, preprocessed exactly as during training.

    raw: images as file paths, bytes, base64 strings or PIL images.
    """
    x = np.stack([image_array(item) for item in raw])
    pipeline = NumericPipeline.__new__(NumericPipeline)
    vars(pipeline).update(INFERENCE_STATE.get("numeric") or {})
    x = pipeline.transform(x)
    if x.ndim == 2 and len(INPUT_SHAPE) > 1 and x.shape[1] == int(np.prod(INPUT_SHAPE)):
        x = x.reshape(len(x), *INPUT_SHAPE)
    if tuple(x.shape[1:]) != tuple(INPUT_SHAPE):
        raise ValueError(f"inputs have shape {tuple(x.shape[1:])}; the model expects "
                         f"{tuple(INPUT_SHAPE)}")
    return x


def image_array(item) -> np.ndarray:
    """An image (path, bytes, base64 string or PIL image) as a [C, H, W] array in [0, 1]."""
    img = open_image(item).convert("L" if INPUT_SHAPE[0] == 1 else "RGB")
    arr = np.asarray(img.resize((INPUT_SHAPE[2], INPUT_SHAPE[1])), dtype=np.float32) / 255.0
    return arr[None] if arr.ndim == 2 else arr.transpose(2, 0, 1)



# =============================================================== metrics
def to_scores(outputs: np.ndarray) -> np.ndarray:
    e = np.exp(outputs - outputs.max(axis=1, keepdims=True))
    return e / e.sum(axis=1, keepdims=True)


def compute_metrics(outputs: np.ndarray, targets: np.ndarray) -> dict:
    """Validation / test metrics from raw model outputs."""
    m = {}
    scores = to_scores(outputs)
    y = (targets.argmax(axis=1) if targets.ndim > 1 else targets).astype(int)
    pred = scores.argmax(axis=1)
    k = scores.shape[1]
    m["accuracy"] = float((pred == y).mean())
    return m


# ============================================================== training
def to_model_layout(x: np.ndarray) -> np.ndarray:
    return np.transpose(x, KERAS_TRANSPOSE) if KERAS_TRANSPOSE and len(x) else x


class EpochReport(keras.callbacks.Callback):
    """Prints one progress line per epoch with validation metrics."""

    def __init__(self, x_val: np.ndarray, y_val: np.ndarray) -> None:
        super().__init__()
        self.x_val, self.y_val, self.started = x_val, y_val, time.time()

    def on_epoch_begin(self, epoch, logs=None) -> None:
        self.started = time.time()

    def on_epoch_end(self, epoch, logs=None) -> None:
        logs = logs or {}
        metrics = {}
        if len(self.x_val):
            metrics = compute_metrics(self.model.predict(self.x_val, verbose=0), self.y_val)
        extra = " ".join(f"{k}={v:.4f}" for k, v in metrics.items() if isinstance(v, float))
        print(f"epoch {epoch + 1}/{EPOCHS} train_loss={logs.get('loss', float('nan')):.4f} "
              f"val_loss={logs.get('val_loss', float('nan')):.4f} {extra} "
              f"({time.time() - self.started:.1f}s)", flush=True)


class SaveResume(keras.callbacks.Callback):
    """After each epoch, what training needs to continue: the weights and optimizer
    (RESUME_FILE), the random state and the other callbacks' counters (early stopping,
    learning-rate plateaus). Listed last, so it restores those after they reset."""

    KEPT = ("wait", "best", "best_weights", "best_epoch", "stopped_epoch", "cooldown_counter")

    def __init__(self, callbacks: list) -> None:
        super().__init__()
        self.callbacks, self.restored = callbacks, None
        self.weights = Path(RESUME_FILE)
        self.extra = self.weights.with_name("resume.extra.pkl")
        self.info = self.weights.with_name("resume.json")   # read by the app, without Keras

    @staticmethod
    def seeds(model: keras.Model) -> list:
        """The layers' random generators (dropout, augmentation): not in the weights."""
        return [g for layer in model._flatten_layers()
                for g in getattr(layer, "_seed_generators", ())]

    def load(self, model: keras.Model) -> int:
        """Restore what on_epoch_end saved; returns the epoch it was saved after."""
        model.optimizer.build(model.trainable_variables)
        model.load_weights(self.weights)
        with open(self.extra, "rb") as fh:
            state = pickle.load(fh)
        for generator, value in zip(self.seeds(model), state["seeds"], strict=True):
            generator.state.assign(value)
        self.restored = state
        print(f"resuming after epoch {state['epoch']}", flush=True)
        return state["epoch"]

    def on_train_begin(self, logs=None) -> None:
        """Just before the first epoch: fit's own setup draws random numbers too."""
        state = self.restored
        if state is None:
            return
        for callback, kept in zip(self.callbacks, state["callbacks"], strict=True):
            callback.__dict__.update(kept)
        random.setstate(state["python"])
        np.random.set_state(state["numpy"])
        if state["torch"] is not None:
            import torch

            torch.set_rng_state(state["torch"]["cpu"])
            if state["torch"]["cuda"] is not None and torch.cuda.is_available():
                torch.cuda.set_rng_state_all(state["torch"]["cuda"])
            if state["torch"]["mps"] is not None and torch.backends.mps.is_available():
                torch.mps.set_rng_state(state["torch"]["mps"])

    def on_epoch_end(self, epoch, logs=None) -> None:
        tmp = self.weights.with_name("resume.tmp.weights.h5")
        self.model.save_weights(tmp, overwrite=True)
        torch_state = None
        if keras.backend.backend() == "torch":
            import torch

            torch_state = {   # unseeded dropout draws on the device's own generator
                "cpu": torch.get_rng_state(),
                "cuda": torch.cuda.get_rng_state_all() if torch.cuda.is_available() else None,
                "mps": torch.mps.get_rng_state() if torch.backends.mps.is_available() else None}
        state = {"epoch": epoch + 1, "python": random.getstate(),
                 "numpy": np.random.get_state(), "torch": torch_state,
                 "seeds": [keras.ops.convert_to_numpy(g.state) for g in self.seeds(self.model)],
                 "callbacks": [{k: v for k, v in vars(c).items() if k in self.KEPT}
                               for c in self.callbacks]}
        with open(self.extra.with_suffix(".tmp"), "wb") as fh:
            pickle.dump(state, fh)
        tmp.replace(self.weights)
        self.extra.with_suffix(".tmp").replace(self.extra)
        self.info.write_text(json.dumps({"epoch": epoch + 1, "epochs": EPOCHS}),
                             encoding="utf-8")


def main() -> None:
    keras.utils.set_random_seed(SEED)
    if MIXED_PRECISION:
        keras.mixed_precision.set_global_policy("mixed_float16")
    arrays = make_arrays()
    (x_train, y_train), (x_val, y_val), (x_test, y_test) = (
        arrays["train"], arrays["val"], arrays["test"])
    x_train, x_val, x_test = map(to_model_layout, (x_train, x_val, x_test))
    print(f"samples: train={len(x_train)} val={len(x_val)} test={len(x_test)}")
    fit_y, val_y = y_train, y_val

    model = build_model()
    print(f"parameters: {model.count_params():,}")
    flat = x_train.reshape(-1, x_train.shape[-1])
    normalize = layers.Normalization(axis=-1, mean=[0.1307], variance=[0.09492561])
    raw = keras.Input(shape=x_train.shape[1:], name="image")
    head = normalize(raw)
    train_model = keras.Model(raw, model(head), name="training_model")
    deploy_model = keras.Model(raw, model(normalize(raw)), name="mnist_mlp_deploy")
    optimizer = keras.optimizers.Adam(learning_rate=0.001, beta_1=0.9, beta_2=0.999, epsilon=1e-08)
    train_model.compile(optimizer=optimizer, loss=keras.losses.SparseCategoricalCrossentropy(from_logits=True), jit_compile=COMPILE)
    callbacks = [EpochReport(x_val, y_val)]
    if EARLY_STOP:
        callbacks.append(keras.callbacks.EarlyStopping(
            monitor="val_loss" if len(x_val) else "loss", patience=EARLY_STOP,
            restore_best_weights=True))
    callbacks.append(keras.callbacks.LearningRateScheduler(lambda epoch, lr: 1e-06 + (LR0 - 1e-06) * (1 + math.cos(math.pi * min(epoch, 50) / 50)) / 2))
    saver = SaveResume(list(callbacks)) if RESUME_FILE else None   # the script's own callbacks
    first_epoch = saver.load(train_model) if saver and RESUME and saver.weights.exists() else 0
    callbacks.extend(CALLBACKS)
    if saver:
        callbacks.append(saver)
    started, finished = train_model.get_weights(), []
    callbacks.append(keras.callbacks.LambdaCallback(on_epoch_end=lambda e, logs: finished.append(e)))
    if COMPILE:
        print("compiling with jit_compile", flush=True)
    while True:
        try:
            train_model.fit(x_train, fit_y, validation_data=(x_val, val_y) if len(x_val) else None,
                            epochs=EPOCHS, batch_size=BATCH_SIZE, callbacks=callbacks, verbose=0,
                            initial_epoch=first_epoch)
            break
        except Exception as exc:  # noqa: BLE001 — a model jit_compile can't take trains without
            if not train_model.jit_compile or finished:
                raise
            print(f"jit_compile did not work ({type(exc).__name__}: {str(exc)[:200]}): "
                  "training without", flush=True)
            train_model.set_weights(started)
            train_model.compile(optimizer=optimizer, loss=keras.losses.SparseCategoricalCrossentropy(from_logits=True), jit_compile=False)
    deploy_model.save(MODEL_FILE)
    save_inference_state()
    try:  # inputs for int8 calibration and export checks (about 4 MB at most)
        per = max(int(np.asarray(x_train[:1]).nbytes), 1)
        calib = {"x": np.asarray(x_train[: max(4, min(128, int(4e6 // per)))])}
        if len(x_test):
            calib["x_eval"] = np.asarray(x_test[: max(4, min(256, int(4e6 // per)))])
            labels = np.asarray(y_test[: len(calib["x_eval"])])
            if labels.ndim == 1:
                calib["y_eval"] = labels.astype(np.int64)
        np.savez_compressed("calibration.npz", **calib)
    except Exception as exc:  # noqa: BLE001 — exports fall back to random inputs
        print(f"(no calibration sample: {exc})")
    print(f"saved model to {MODEL_FILE}")
    outputs = deploy_model.predict(x_test, verbose=0) if len(x_test) else np.zeros((0,))
    metrics = compute_metrics(outputs, y_test) if len(x_test) else {}
    print("test: " + " ".join(f"{k}={v:.4f}" for k, v in metrics.items() if isinstance(v, float)))
    Path("metrics.json").write_text(json.dumps(metrics, indent=1), encoding="utf-8")
    if RESUME_FILE:             # trained and scored: nothing to resume
        for name in (RESUME_FILE, "resume.extra.pkl", "resume.json"):
            Path(name).unlink(missing_ok=True)
    probs = to_scores(outputs)
    items = [{"index": i, "true": (y_test[i].tolist() if np.ndim(y_test[i]) else int(y_test[i])),
              "probs": [round(float(v), 4) for v in probs[i]], "file": None}
             for i in range(min(len(probs), 300))]
    Path("predictions.json").write_text(json.dumps(items, indent=1), encoding="utf-8")
    mistakes = [it for it in items if int(np.argmax(it["probs"])) != it["true"]]
    Path("mistakes.json").write_text(json.dumps(mistakes[:50], indent=1), encoding="utf-8")
    print(f"saved predictions.json ({len(items)} examples)")


