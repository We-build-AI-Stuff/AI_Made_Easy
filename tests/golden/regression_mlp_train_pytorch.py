def pick_device() -> torch.device:
    if WORLD > 1:   # one GPU per process (CPU processes when DEVICE is "cpu")
        return torch.device("cuda", RANK) if DEVICE != "cpu" else torch.device("cpu")
    if DEVICE != "auto":
        return torch.device(DEVICE)
    if torch.cuda.is_available():
        return torch.device("cuda")
    if torch.backends.mps.is_available():
        return torch.device("mps")
    return torch.device("cpu")


def adapt(out: torch.Tensor, y: torch.Tensor):
    """Align output and target shapes for the loss."""
    if out.ndim == 2 and out.shape[1] == 1 and y.ndim == 1:
        out = out[:, 0]
    return out, y.float()


def make_loss(train_targets: np.ndarray | None = None):
    return nn.SmoothL1Loss(beta=1.0)


@torch.no_grad()
def predict(model: nn.Module, loader: DataLoader, device: torch.device):
    model.eval()
    outs, ys = [], []
    for xb, yb in loader:
        outs.append(model(xb.to(device)).float().cpu())
        ys.append(yb)
    if not outs:
        return np.zeros((0,)), np.zeros((0,))
    return torch.cat(outs).numpy(), torch.cat(ys).numpy()


def evaluate(model: nn.Module, loss_fn, loader: DataLoader, device: torch.device):
    outputs, targets = predict(model, loader, device)
    if len(outputs) == 0:
        return float("nan"), {}
    with torch.no_grad():
        out_t, y_t = adapt(torch.from_numpy(outputs), torch.from_numpy(targets))
        loss = float(loss_fn(out_t, y_t))
    return loss, compute_metrics(outputs, targets)


def reset_peak_memory(device: torch.device) -> None:
    if device.type == "cuda":
        torch.cuda.reset_peak_memory_stats(device)


def report_resources(device: torch.device, step_seconds: float) -> None:
    """Measured first-epoch cost; calibrates the designer's budget estimates."""
    peak = 0.0
    if device.type == "cuda":
        peak = torch.cuda.max_memory_allocated(device) / 2**20
    elif device.type == "mps":
        peak = torch.mps.driver_allocated_memory() / 2**20
    print(f"resources: peak_memory_mb={peak:.1f} step_ms={step_seconds * 1e3:.2f} "
          f"batch_size={BATCH_SIZE} device={device.type}", flush=True)


class GeneratorState:
    """A random generator saved and restored like a module (the loader's shuffle order)."""

    def __init__(self, generator: torch.Generator) -> None:
        self.generator = generator

    def state_dict(self) -> torch.Tensor:
        return self.generator.get_state()

    def load_state_dict(self, state: torch.Tensor) -> None:
        self.generator.set_state(state.cpu())


def save_resume(epoch: int, objects: dict, best: tuple) -> None:
    """The model, optimizer and the rest after ``epoch``, written atomically."""
    state = {name: obj.state_dict() for name, obj in objects.items()}
    state.update(epoch=epoch, best=best, rng={
        "torch": torch.get_rng_state(), "numpy": np.random.get_state(),
        "cuda": torch.cuda.get_rng_state_all() if torch.cuda.is_available() else None,
        "mps": torch.mps.get_rng_state() if torch.backends.mps.is_available() else None})
    tmp = Path(RESUME_FILE + ".tmp")
    torch.save(state, tmp)
    tmp.replace(RESUME_FILE)
    info = Path(RESUME_FILE).with_suffix(".json")   # read by the app, without torch
    info.with_suffix(".json.tmp").write_text(json.dumps({"epoch": epoch, "epochs": EPOCHS}),
                                             encoding="utf-8")
    info.with_suffix(".json.tmp").replace(info)   # a stop mid-write leaves the last one whole


def load_resume(objects: dict, device) -> tuple[int, tuple]:  # noqa: ANN001
    """Restore what save_resume wrote; returns the epoch it was saved after."""
    state = torch.load(RESUME_FILE, map_location=device, weights_only=False)
    for name, obj in objects.items():
        obj.load_state_dict(state[name])
    torch.set_rng_state(state["rng"]["torch"].cpu())
    np.random.set_state(state["rng"]["numpy"])
    if state["rng"]["cuda"] is not None and torch.cuda.is_available():
        torch.cuda.set_rng_state_all([s.cpu() for s in state["rng"]["cuda"]])
    if state["rng"].get("mps") is not None and torch.backends.mps.is_available():
        torch.mps.set_rng_state(state["rng"]["mps"].cpu())
    print(f"resuming after epoch {state['epoch']}", flush=True)
    return state["epoch"], state["best"]


class Compiled:
    """The training steps through torch.compile; plain PyTorch when compiling fails (a
    layer, platform or Python version it doesn't support), saying why."""

    def __init__(self, model) -> None:  # noqa: ANN001
        self.model, self.fast, self.working = model, None, False
        try:
            self.fast = torch.compile(model)
        except Exception as exc:  # noqa: BLE001
            self.failed(exc)

    def failed(self, exc: Exception) -> None:
        self.fast = None
        first = (str(exc).strip().splitlines() or [type(exc).__name__])[0]
        print(f"torch.compile did not work, training without it: {first[:300]}", flush=True)

    def __call__(self, x: torch.Tensor) -> torch.Tensor:
        if self.fast is not None:
            try:
                out = self.fast(x)
            except Exception as exc:  # noqa: BLE001 — compiling happens at the first call
                self.failed(exc)
            else:
                if not self.working:
                    self.working = True
                    print("compiled with torch.compile", flush=True)
                return out
        return self.model(x)


def checkpoint_layers(model: nn.Module) -> int:
    """Recompute each layer's activations in the backward pass instead of keeping them.
    Layers with batch norm keep theirs (recomputing would update its statistics twice)."""
    from torch.utils.checkpoint import checkpoint

    count = 0
    for layer in model.children():
        if (isinstance(layer, (nn.ModuleList, nn.ModuleDict))
                or not any(p.requires_grad for p in layer.parameters())
                or any(isinstance(m, nn.modules.batchnorm._BatchNorm) for m in layer.modules())):
            continue

        def recomputed(*args, _forward=layer.forward, _layer=layer, **kwargs):  # noqa: ANN002, ANN003, ANN202
            if _layer.training and torch.is_grad_enabled():
                return checkpoint(_forward, *args, use_reentrant=False, **kwargs)
            return _forward(*args, **kwargs)

        layer.forward = recomputed
        count += 1
    return count


def train_together(gpus: int) -> None:
    """Train on several GPUs of this machine, with gradients averaged by
    DistributedDataParallel. This process trains as the first one, which reports and
    saves; the others are forked (spawned on Windows, which can't fork) and only train."""
    import json
    import socket
    import subprocess

    import torch.multiprocessing as mp

    here = gpus
    if DEVICE != "cpu":   # counted in another process: CUDA started here would break the fork
        python = sys.executable   # this script's interpreter: the one with torch
        counted = subprocess.run([python, "-c", "import torch; print(torch.cuda.device_count())"],
                                 capture_output=True, encoding="utf-8", errors="replace",
                                 check=False)
        words = counted.stdout.split()
        here = int(words[-1]) if counted.returncode == 0 and words else 0
    count = min(gpus, here)
    if count < 2:
        print(f"training on one device: {GPUS} GPUs asked for, {here} CUDA GPU(s) here",
              flush=True)
        globals()["GPUS"] = 1
        main()
        return
    with socket.socket() as probe:   # a free port for the processes to meet on
        probe.bind(("127.0.0.1", 0))
        port = probe.getsockname()[1]

    def plain(value) -> bool:  # noqa: ANN001
        try:
            json.dumps(value)
            return True
        except (TypeError, ValueError):
            return False

    # a spawned process starts from this file: it gets the settings changed since
    settings = {k: v for k, v in globals().items() if k.isupper() and plain(v)}
    dropped = sorted(k for k, v in globals().items()
                     if k.isupper() and v is not None and k not in settings)
    if START_METHOD != "fork" and dropped:
        print(f"warning: {', '.join(dropped)} can't be passed to the other processes here "
              "(they start from this file): they train without them", flush=True)
    print(f"training on {count} {'CPU processes' if DEVICE == 'cpu' else 'GPUs'} "
          "(DistributedDataParallel)", flush=True)
    sys.stdout.flush()
    others = mp.start_processes(_one_of_many, args=(count, port, settings), nprocs=count - 1,
                                join=False, start_method=START_METHOD)
    done = threading.Event()
    threading.Thread(target=_watch, args=(others.processes, done), daemon=True).start()

    def stop_others() -> None:   # they would wait for this one until the backend times out
        done.set()
        _stop(others.processes)

    try:
        _train_as(0, count, port, stop_others)
    except BaseException:
        stop_others()
        raise
    done.set()
    while not others.join():
        pass


def _stop(processes: list) -> None:
    for process in processes:
        if process.is_alive():
            process.terminate()


def _watch(processes: list, done: threading.Event) -> None:
    """While this process trains, notice another one failing: this one would wait for it
    in the next exchange until the backend times out."""
    import os

    while not done.wait(1.0):
        failed = next((p for p in processes if p.exitcode not in (None, 0)), None)
        if failed is not None:
            print(f"a training process stopped (exit code {failed.exitcode}): stopping the "
                  "run", flush=True)
            _stop(processes)
            os._exit(1)


START_METHOD = "spawn" if sys.platform == "win32" else "fork"


def _one_of_many(index: int, world: int, port: int, settings: dict) -> None:
    """Process ``index + 1`` of ``world``: trains its share, reports nothing."""
    import os

    globals().update(settings)
    sys.stdout = open(os.devnull, "w", encoding="utf-8")  # noqa: SIM115
    _train_as(index + 1, world, port)


def _train_as(rank: int, world: int, port: int, on_failure=None) -> None:  # noqa: ANN001
    import torch.distributed as dist

    global RANK, WORLD
    RANK, WORLD = rank, world
    gpu = DEVICE != "cpu"
    if gpu:
        torch.cuda.set_device(rank)
    backend = "nccl" if gpu and sys.platform != "win32" else "gloo"   # no NCCL on Windows
    dist.init_process_group(backend, init_method=f"tcp://127.0.0.1:{port}", rank=rank,
                            world_size=world)
    try:
        main()
    except BaseException:
        if on_failure is not None:
            on_failure()   # first, before anything can wait on the other processes
        raise              # no teardown: it can wait on processes that are gone
    dist.destroy_process_group()


def mean_across(grad: torch.Tensor, group) -> torch.Tensor:  # noqa: ANN001
    """A gradient averaged over the processes training together."""
    grad = grad.clone()
    torch.distributed.all_reduce(grad, group=group)
    return grad / WORLD


def fit(model: nn.Module, train_loader, val_loader, device, log: bool = True):
    """Train with early stopping on validation loss; returns the best state."""
    loss_fn = make_loss()
    if hasattr(loss_fn, "to"):
        loss_fn = loss_fn.to(device)
    params = PARAM_GROUPS(model) if PARAM_GROUPS is not None else model.parameters()
    optimizer = torch.optim.Adam(params, lr=0.001, betas=(0.9, 0.999), eps=1e-08)
    for group in optimizer.param_groups:
        group["lr"] *= LR_SCALE * group.get("lr_mult", 1.0)
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=50, eta_min=1e-06)
    use_amp = MIXED_PRECISION and device.type in ("cuda", "mps")
    amp_dtype = torch.float16 if device.type == "cuda" else torch.bfloat16
    scaler = torch.amp.GradScaler("cuda", enabled=use_amp and device.type == "cuda")
    net = model   # what the training steps call
    if WORLD > 1:
        net = nn.parallel.DistributedDataParallel(
            model, device_ids=[device.index] if device.type == "cuda" else None,
            # experts a batch never routes to get no gradient
            find_unused_parameters=any(hasattr(m, "aux_loss") for m in model.modules()))
    if COMPILE:
        net = Compiled(net)
    best_loss, best_state, bad_epochs = float("inf"), None, 0
    reset_peak_memory(device)
    resumable = {"model": model, "optimizer": optimizer, "scaler": scaler}
    shuffle = (getattr(train_loader, "generator", None)
               or getattr(train_loader.sampler, "generator", None))
    if shuffle is not None:
        resumable["shuffle"] = GeneratorState(shuffle)
    resumable["scheduler"] = scheduler
    first_epoch = 1
    if log and RESUME and RESUME_FILE and Path(RESUME_FILE).exists():
        done, (best_loss, best_state, bad_epochs) = load_resume(resumable, device)
        first_epoch = done + 1
    for epoch in range(first_epoch, EPOCHS + 1):
        if EPOCH_HOOK is not None:
            EPOCH_HOOK(epoch, model)
        if hasattr(train_loader.sampler, "set_epoch"):
            train_loader.sampler.set_epoch(epoch)   # a new shuffle for every epoch
        model.train()
        started, running, seen = time.time(), 0.0, 0
        optimizer.zero_grad(set_to_none=True)
        step = 0
        for step, (xb, yb) in enumerate(train_loader, start=1):
            xb, yb = xb.to(device), yb.to(device)
            with torch.autocast(device_type=device.type, dtype=amp_dtype, enabled=use_amp):
                out, target = adapt(net(xb), yb)
                loss = loss_fn(out, target)
                if LOSS_HOOK is not None:
                    loss = LOSS_HOOK(loss, out, xb, model)
            scaler.scale(loss / ACCUM_STEPS).backward()
            if step % ACCUM_STEPS == 0 or step == len(train_loader):
                if GRAD_CLIP > 0:
                    scaler.unscale_(optimizer)
                    nn.utils.clip_grad_norm_(model.parameters(), GRAD_CLIP)
                scaler.step(optimizer)
                scaler.update()
                optimizer.zero_grad(set_to_none=True)
            if BATCH_HOOK is not None:
                BATCH_HOOK(optimizer, loss.item())
            running += loss.item() * len(xb)
            seen += len(xb)
        if epoch == 1 and log:
            report_resources(device, (time.time() - started) / max(step, 1))
        if WORLD > 1:   # the loss over every process's share
            totals = torch.tensor([running, float(seen)], device=device)
            torch.distributed.all_reduce(totals)
            running, seen = totals.tolist()
        train_loss = running / max(seen, 1)
        val_loss, val_metrics = evaluate(model, loss_fn, val_loader, device)
        if WORLD > 1:   # every process decides (schedule, best, stop) from the first one's
            shared = torch.tensor([val_loss], dtype=torch.float64, device=device)
            torch.distributed.broadcast(shared, 0)
            val_loss = shared.item()
        monitored = val_loss if not math.isnan(val_loss) else train_loss
        scheduler.step()
        if log:
            extra = " ".join(f"{k}={v:.4f}" for k, v in val_metrics.items()
                             if isinstance(v, float))
            lr = optimizer.param_groups[0]["lr"]
            print(f"epoch {epoch}/{EPOCHS} train_loss={train_loss:.4f} val_loss={val_loss:.4f} "
                  f"{extra} lr={lr:.3g} ({time.time() - started:.1f}s)", flush=True)
        if monitored < best_loss:
            best_loss, bad_epochs = monitored, 0
            best_state = {k: v.detach().cpu().clone() for k, v in model.state_dict().items()}
        else:
            bad_epochs += 1
            if EARLY_STOP and bad_epochs >= EARLY_STOP:
                if log:
                    print(f"early stopping: no improvement for {EARLY_STOP} epochs")
                break
        if log and RESUME_FILE and RANK == 0:
            save_resume(epoch, resumable, (best_loss, best_state, bad_epochs))
    if best_state is not None:
        model.load_state_dict(best_state)
    return model, loss_fn


