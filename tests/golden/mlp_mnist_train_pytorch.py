class MnistMlp(nn.Module):
    r"""(batch, 1, 28, 28) -> (batch, 10)."""

    def __init__(self) -> None:
        super().__init__()
        self.flatten_1 = nn.Flatten()
        self.dense_1 = nn.Linear(in_features=784, out_features=128, bias=True)
        self.relu_1 = nn.ReLU()
        self.dropout_1 = nn.Dropout(p=0.2)
        self.dense_2 = nn.Linear(in_features=128, out_features=10, bias=True)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        x = self.flatten_1(x)
        x = self.dense_1(x)
        x = self.relu_1(x)
        x = self.dropout_1(x)
        x = self.dense_2(x)
        return x


